"""Corruption ladder (milestone2-plan.md §1.6).

Every operator is declared in ``corruption/ladder.yaml`` with a ``preserves_match``
contract. Generation is deterministic given the seed. Header renames are recorded in a
map so ground truth can be composed through them.

The integrity check answers one question: after corruption, is the correspondence still
recoverable *in principle*? It uses a deliberately aggressive canonicalisation, because it
is proving recoverability, not demonstrating our preview implementation.
"""

from __future__ import annotations

import random
import re
from dataclasses import dataclass, field
from pathlib import Path

import pandas as pd
import yaml
from pandas import DataFrame, Series

# --------------------------------------------------------------------------- specs


@dataclass(frozen=True)
class OperatorSpec:
    id: str
    dimension: str
    target: str
    preserves_match: bool
    repair: str | None
    params: dict = field(default_factory=dict)


def load_ladder(path: str | Path = "corruption/ladder.yaml") -> dict:
    with Path(path).open(encoding="utf-8") as fh:
        return yaml.safe_load(fh) or {}


def parse_level(ladder: dict, level: str) -> list[OperatorSpec]:
    raw = (ladder.get("levels") or {}).get(level)
    if raw is None:
        raise KeyError(f"level {level!r} not in ladder")
    return [
        OperatorSpec(
            id=op["id"],
            dimension=raw.get("dimension", ""),
            target=op.get("target", "both"),
            preserves_match=bool(op.get("preserves_match", True)),
            repair=op.get("repair"),
            params=op.get("params") or {},
        )
        for op in raw.get("operators") or []
    ]


# ----------------------------------------------------------------------- header ops

UNIT_SUFFIXES = ["(kg)", "[USD]", "/day", "%", "(cm)"]


def _op_autogenerated_name(df: DataFrame, rng: random.Random, params: dict) -> tuple[DataFrame, dict]:
    patterns = params.get("patterns") or ["Unnamed: {i}", "col_{i}"]
    mapping = {}
    for i, col in enumerate(df.columns):
        if rng.random() < 0.5:
            new = rng.choice(patterns).format(i=i)
            if new not in df.columns and new not in mapping.values():
                mapping[str(col)] = new
    return df.rename(columns=mapping), mapping


def _op_append_unit_to_header(df: DataFrame, rng: random.Random, params: dict) -> tuple[DataFrame, dict]:
    units = params.get("units") or UNIT_SUFFIXES
    mapping = {
        str(col): f"{col} {rng.choice(units)}"
        for col in df.columns
        if rng.random() < 0.4
    }
    return df.rename(columns=mapping), mapping


def _op_reorder_columns(df: DataFrame, rng: random.Random, params: dict) -> tuple[DataFrame, dict]:
    cols = list(df.columns)
    rng.shuffle(cols)
    return df[cols], {}


def _op_duplicate_header(df: DataFrame, rng: random.Random, params: dict) -> tuple[DataFrame, dict]:
    if len(df.columns) < 2:
        return df, {}
    i, j = rng.sample(range(len(df.columns)), 2)
    mapping = {str(df.columns[j]): str(df.columns[i])}
    return df.rename(columns=mapping), mapping


def _op_add_spurious_column(df: DataFrame, rng: random.Random, params: dict) -> tuple[DataFrame, dict]:
    name = f"extra_{len(df.columns)}"
    while name in df.columns:
        name += "_x"
    return df.assign(**{name: rng.randint(0, 9)}), {}


SYNONYMS = {
    "customer": "client", "client": "customer", "order": "purchase",
    "product": "item", "price": "amount", "date": "timestamp",
    "city": "town", "state": "region", "name": "title", "id": "identifier",
}
ABBREVIATIONS = {
    "customer": "cust", "product": "prod", "identifier": "id", "timestamp": "ts",
    "order": "ord", "payment": "pay", "category": "cat", "description": "desc",
}
TRANSLATIONS = {
    "pt": {"order": "pedido", "customer": "cliente", "product": "produto",
           "price": "preco", "date": "data", "name": "nome", "city": "cidade",
           "state": "estado", "value": "valor"},
    "es": {"order": "pedido", "customer": "cliente", "product": "producto",
           "price": "precio", "date": "fecha", "name": "nombre", "city": "ciudad",
           "state": "estado", "value": "valor"},
}

# Starter lexicons. Deliberately small and visible: M3 extends them with a reviewable
# file under data/lexicon/ rather than hiding a growing dictionary in code.
VALUE_SYNONYMS = {
    "credit_card": "CC", "debit_card": "DC", "boleto": "ticket",
    "voucher": "coupon", "SP": "Sao Paulo", "RJ": "Rio de Janeiro",
    "MG": "Minas Gerais",
}


def _rename_tokens(col: str, table: dict[str, str]) -> str:
    parts = re.split(r"([_\s\-]+)", str(col))
    return "".join(table.get(p.lower(), p) if p not in ("_", " ", "-") else p for p in parts)


def _op_rename_synonym(df: DataFrame, rng: random.Random, params: dict) -> tuple[DataFrame, dict]:
    mapping = {
        str(col): _rename_tokens(col, SYNONYMS)
        for col in df.columns
        if rng.random() < 0.5
    }
    mapping = {k: v for k, v in mapping.items() if k != v}
    return df.rename(columns=mapping), mapping


def _op_rename_abbreviate(df: DataFrame, rng: random.Random, params: dict) -> tuple[DataFrame, dict]:
    mapping = {}
    for col in df.columns:
        if rng.random() < 0.5:
            renamed = _rename_tokens(col, ABBREVIATIONS)
            if renamed != str(col):
                mapping[str(col)] = renamed
    return df.rename(columns=mapping), mapping


def _op_rename_translate(df: DataFrame, rng: random.Random, params: dict) -> tuple[DataFrame, dict]:
    languages = params.get("languages") or ["pt"]
    table = TRANSLATIONS.get(rng.choice(languages), {})
    mapping = {}
    for col in df.columns:
        if rng.random() < 0.4:
            renamed = _rename_tokens(col, table)
            if renamed != str(col):
                mapping[str(col)] = renamed
    return df.rename(columns=mapping), mapping


HEADER_OPS = {
    "autogenerated_name": _op_autogenerated_name,
    "append_unit_to_header": _op_append_unit_to_header,
    "reorder_columns": _op_reorder_columns,
    "duplicate_header": _op_duplicate_header,
    "add_spurious_column": _op_add_spurious_column,
    "rename_synonym": _op_rename_synonym,
    "rename_abbreviate": _op_rename_abbreviate,
    "rename_translate": _op_rename_translate,
}

# ------------------------------------------------------------------------ value ops


def _op_floatify(s: Series, rng: random.Random, params: dict) -> Series:
    return s.map(lambda v: f"{v}.0" if isinstance(v, (int, float)) and float(v).is_integer() else v)


def _op_zero_pad(s: Series, rng: random.Random, params: dict) -> Series:
    width = int(params.get("width", 8))
    return s.map(lambda v: str(v).zfill(width) if str(v).isdigit() else v)


def _op_id_prefix(s: Series, rng: random.Random, params: dict) -> Series:
    prefix = rng.choice(params.get("prefixes") or ["ORD-"])
    return s.map(lambda v: f"{prefix}{v}" if pd.notna(v) else v)


def _op_number_thousand_separator(s: Series, rng: random.Random, params: dict) -> Series:
    def fmt(v: object) -> object:
        if isinstance(v, (int, float)) and not isinstance(v, bool):
            return f"{v:,}"
        return v

    return s.map(fmt)


def _op_currency_symbol(s: Series, rng: random.Random, params: dict) -> Series:
    symbol = rng.choice(params.get("symbols") or ["$"])
    return s.map(lambda v: f"{symbol}{v}" if isinstance(v, (int, float)) else v)


def _op_sentinel_null(s: Series, rng: random.Random, params: dict) -> Series:
    tokens = params.get("tokens") or ["N/A", "-", "unknown"]
    return s.map(lambda v: rng.choice(tokens) if pd.isna(v) else v)


def _op_whitespace_pad(s: Series, rng: random.Random, params: dict) -> Series:
    return s.map(
        lambda v: f"{' ' * rng.randint(0, 2)}{v}{' ' * rng.randint(0, 2)}"
        if isinstance(v, str)
        else v
    )


def _op_case_variation_values(s: Series, rng: random.Random, params: dict) -> Series:
    styles = params.get("styles") or ["upper", "lower"]

    def fmt(value: object) -> object:
        if not isinstance(value, str):
            return value
        style = rng.choice(styles)
        if style == "mixed":
            return value.swapcase()
        return getattr(value, style, str.lower)()

    return s.map(fmt)


def _op_unit_in_value(s: Series, rng: random.Random, params: dict) -> Series:
    units = params.get("units") or ["kg"]
    unit = rng.choice(units)
    return s.map(lambda v: f"{v} {unit}" if isinstance(v, (int, float)) else v)


def _op_date_reformat(s: Series, rng: random.Random, params: dict) -> Series:
    parsed = pd.to_datetime(s, errors="coerce", format="mixed")
    if parsed.notna().mean() < 0.5:
        return s
    style = rng.choice(["iso", "slash", "european", "long_text"])

    def fmt(value: pd.Timestamp) -> object:
        if pd.isna(value):
            return value
        if style == "iso":
            return value.strftime("%Y-%m-%dT%H:%M:%S")
        if style == "slash":
            return value.strftime("%m/%d/%Y")
        if style == "european":
            return value.strftime("%d.%m.%Y")
        return value.strftime("%d %b %Y")

    return parsed.map(fmt)


def _op_number_decimal_comma(s: Series, rng: random.Random, params: dict) -> Series:
    def fmt(v: object) -> object:
        if isinstance(v, float):
            return str(v).replace(".", ",")
        if isinstance(v, int) and not isinstance(v, bool):
            return f"{v},0"
        return v

    return s.map(fmt)


def _op_mixed_type_in_column(s: Series, rng: random.Random, params: dict) -> Series:
    fraction = float(params.get("fraction", 0.05))
    tokens = ["n/a", "see notes", "", "-"]
    mask = [rng.random() < fraction for _ in range(len(s))]
    return Series(
        [rng.choice(tokens) if hit else value for hit, value in zip(mask, s)],
        index=s.index,
    )


def _op_unicode_variants(s: Series, rng: random.Random, params: dict) -> Series:
    def fmt(v: object) -> object:
        if not isinstance(v, str):
            return v
        v = v.replace("-", "–")
        v = v.replace("'", "’")
        return v.replace(" ", " ")

    return s.map(fmt)


def _op_synonym_substitute(s: Series, rng: random.Random, params: dict) -> Series:
    return s.map(lambda v: VALUE_SYNONYMS.get(str(v), v) if isinstance(v, str) else v)


def _op_translate_values(s: Series, rng: random.Random, params: dict) -> Series:
    reverse = {v: k for k, v in VALUE_SYNONYMS.items()}
    return s.map(lambda v: reverse.get(str(v), v) if isinstance(v, str) else v)


def _op_category_recode(s: Series, rng: random.Random, params: dict) -> Series:
    values = s.dropna().astype(str).unique()
    if len(values) > 50:  # only recode genuinely categorical columns
        return s
    mapping = {value: f"cat_{i}" for i, value in enumerate(sorted(values))}
    return s.map(lambda v: mapping.get(str(v), v) if isinstance(v, str) else v)


VALUE_OPS = {
    "floatify": _op_floatify,
    "zero_pad": _op_zero_pad,
    "id_prefix": _op_id_prefix,
    "number_thousand_separator": _op_number_thousand_separator,
    "number_decimal_comma": _op_number_decimal_comma,
    "currency_symbol": _op_currency_symbol,
    "sentinel_null": _op_sentinel_null,
    "whitespace_pad": _op_whitespace_pad,
    "case_variation_values": _op_case_variation_values,
    "unit_in_value": _op_unit_in_value,
    "date_reformat": _op_date_reformat,
    "mixed_type_in_column": _op_mixed_type_in_column,
    "unicode_variants": _op_unicode_variants,
    "synonym_substitute": _op_synonym_substitute,
    "translate_values": _op_translate_values,
    "category_recode": _op_category_recode,
}


# --------------------------------------------------------------------------- apply


@dataclass
class Corrupted:
    df: DataFrame
    level: str
    rename_map: dict[str, str]
    applied: list[str]

    def remap_column(self, original: str) -> str:
        return self.rename_map.get(original, original)


def apply_level(
    df: DataFrame,
    level: str,
    ladder: dict | None = None,
    seed: int = 42,
    column_fraction: float = 0.5,
) -> Corrupted:
    """Apply every operator declared for ``level`` to a copy of ``df``."""
    ladder = ladder if ladder is not None else load_ladder()
    specs = parse_level(ladder, level)
    rng = random.Random(seed)

    out = df.copy()
    rename_map: dict[str, str] = {}
    applied: list[str] = []

    if level == "L0" or not specs:
        return Corrupted(out, level, rename_map, applied)

    def merge_renames(mapping: dict[str, str]) -> None:
        """Compose renames so the map always goes original -> final.

        Intermediate names never become keys: if a name being renamed was produced by an
        earlier operator, the update lands on the original column instead. Collisions are
        allowed — `duplicate_header` deliberately gives two columns the same name, and the
        ground truth then has to be keyed by position rather than by name.
        """
        for old, new in mapping.items():
            if old in rename_map:
                rename_map[old] = new
                continue
            owners = [original for original, current in rename_map.items() if current == old]
            if owners:
                for original in owners:
                    rename_map[original] = new
            else:
                rename_map[old] = new

    for spec in specs:
        if spec.id in HEADER_OPS:
            out, mapping = HEADER_OPS[spec.id](out, rng, spec.params)
            merge_renames(mapping)
        elif spec.id in VALUE_OPS:
            cols = [c for c in out.columns if rng.random() < column_fraction]
            for col in cols:
                out[col] = VALUE_OPS[spec.id](out[col], rng, spec.params)
        else:
            # Declared but not implemented yet — fail loudly rather than silently
            # producing a level that is weaker than the config claims.
            raise NotImplementedError(
                f"operator {spec.id!r} is declared in the ladder but not implemented "
                "in swsn.corrupt; add it to HEADER_OPS or VALUE_OPS"
            )
        applied.append(spec.id)

    return Corrupted(out, level, rename_map, applied)


# ------------------------------------------------------------------- integrity check


def _aggressive_canonical(value: object) -> str:
    """Strip everything a canonicaliser could plausibly remove.

    Used only by the integrity check: it asks whether the correspondence is recoverable
    in principle, so it is allowed to be more powerful than the preview in `normalize`.
    Numeric values go through the preview canonicaliser first so that 1001, 1001.0 and
    1,001 all collapse to the same token.
    """
    from .normalize import canonicalise_value

    text = str(value).strip().casefold()

    canonical = canonicalise_value(text)
    if re.fullmatch(r"-?\d+(\.\d+)?", canonical):
        return canonical

    stripped = re.sub(r"^(ord|id|key|k)[^0-9a-z]*", "", text)
    canonical = canonicalise_value(stripped)
    if re.fullmatch(r"-?\d+(\.\d+)?", canonical):
        return canonical

    text = re.sub(r"[^0-9a-z]", "", stripped.replace(",", "").replace("_", ""))
    return text.lstrip("0") or "0"


def check_preservation(
    df_a: DataFrame,
    df_b: DataFrame,
    correspondences: list[tuple[str, str]],
    threshold: float = 0.5,
) -> list[str]:
    """Return a message per correspondence whose value overlap collapsed.

    ``correspondences`` is a list of (column_in_a, column_in_b) using the *original*
    names of both tables.
    """
    violations = []
    for col_a, col_b in correspondences:
        if col_a not in df_a.columns or col_b not in df_b.columns:
            continue
        sa = {_aggressive_canonical(v) for v in df_a[col_a].dropna().astype(str)}
        sb = {_aggressive_canonical(v) for v in df_b[col_b].dropna().astype(str)}
        if not sa or not sb:
            continue
        overlap = len(sa & sb) / len(sa | sb)
        if overlap < threshold:
            violations.append(f"{col_a} <-> {col_b}: overlap {overlap:.2f} < {threshold}")
    return violations
