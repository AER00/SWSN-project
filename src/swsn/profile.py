"""Dirtiness profiling — dimensions D1-D7.

These are v1 heuristics, deliberately simple and explainable: every number has to be
defensible in the report, so nothing here is a learned score. Refine in M3 if a dimension
turns out to discriminate poorly.
"""

from __future__ import annotations

import re
from dataclasses import asdict, dataclass

import pandas as pd

AUTOGENERATED = re.compile(r"^(unnamed:?\s*\d+|col_?\d+|v\d+|field\d+|column\d+)$", re.IGNORECASE)
SENTINELS = {"n/a", "na", "-", "--", "unknown", "?", "null", "none", "", "nan", "999", "-1"}


@dataclass(frozen=True)
class ColumnProfile:
    name: str
    # D2 type instability
    numeric_coercion_rate: float
    date_coercion_rate: float
    mixed_type: bool
    # D3 missingness and sentinels
    missing_rate: float
    sentinel_rate: float
    # D4 format heterogeneity
    format_shapes: int
    # D5 categorical noise
    categorical_variants: int
    # D6 cardinality and texture
    n_unique: int
    unique_ratio: float
    mean_token_length: float
    # D7 distribution shape (only meaningful when the column parses as numeric)
    skew: float
    zero_inflation: float
    outlier_rate: float
    # D1 header noise (0 = clean name, 1 = unusable name)
    name_score: float
    name_flags: list[str]

    def as_dict(self) -> dict:
        return asdict(self)


def _value_shapes(series: pd.Series, limit: int = 2000) -> int:
    """Distinct structural shapes of the values: digits -> 9, letters -> a, runs collapsed.

    A column holding both ``1,234.5`` and ``1234.50`` yields two shapes — that is the
    point: this counts encoding heterogeneity, not value heterogeneity.

    Runs are collapsed before counting. Without that step every free-text and hex-identifier
    value produces its own shape (``06b8999e`` and ``1e9e8ef0`` are both 32 characters but
    alternate between letters and digits differently), ``format_shapes`` grew with the row
    count, and a threshold on it flagged every column in every table. Collapsing runs makes
    the statistic depend on the *grammar* of the value, which is what D4 is about.
    """
    sample = series.dropna().astype(str).head(limit)
    shapes = set()
    for value in sample:
        shape = re.sub(r"\d", "9", re.sub(r"[A-Za-z]", "a", value.strip()))
        shape = re.sub(r"(9)\1+", r"9", shape)
        shape = re.sub(r"(a)\1+", r"a", shape)
        shapes.add(shape)
    return len(shapes)


def _name_flags(name: str) -> list[str]:
    flags = []
    if AUTOGENERATED.match(name.strip()):
        flags.append("autogenerated")
    if any(ord(ch) > 127 for ch in name):
        flags.append("non_ascii")
    if re.search(r"[\(\[].*[\)\]]", name):
        flags.append("unit_in_header")
    if " " in name.strip():
        flags.append("spaces")
    if re.search(r"[A-Z]", name) and re.search(r"[a-z]", name) and "_" not in name:
        flags.append("camel_case")
    if len(name) <= 3:
        flags.append("abbreviated")
    return flags


def _shape_moments(numeric: pd.Series) -> tuple[float, float, float]:
    """Skew, zero-inflation and IQR-outlier share of an already-coerced numeric series.

    These three are what ``DistributionBased`` actually reacts to: a heavily skewed column
    and a symmetric one with the same mean look different to it, and a column that is 80 %
    zeros has a distribution shape no histogram binning will recover. Returned as zeros
    when the column has no usable numeric content, which is the honest answer rather than
    a NaN that would propagate into every aggregate.
    """
    if len(numeric) < 3:
        return 0.0, 0.0, 0.0
    q1, q3 = numeric.quantile([0.25, 0.75])
    iqr = float(q3 - q1)
    if iqr > 0:
        outlier = float(((numeric < q1 - 1.5 * iqr) | (numeric > q3 + 1.5 * iqr)).mean())
    else:
        outlier = 0.0
    return (
        float(numeric.skew()) if len(numeric) > 2 else 0.0,
        float((numeric == 0).mean()),
        outlier,
    )


def profile_column(series: pd.Series, name: str | None = None) -> ColumnProfile:
    name = name if name is not None else str(series.name)
    values = series.dropna()
    n = max(len(series), 1)
    non_null = max(len(values), 1)

    as_text = values.astype(str).str.strip()
    numeric = pd.to_numeric(as_text.str.replace(",", ".", regex=False), errors="coerce")
    dates = pd.to_datetime(as_text, errors="coerce", format="mixed")

    lowered = as_text.str.lower()
    sentinel_hits = lowered.isin(SENTINELS).sum()
    n_unique = int(values.nunique(dropna=True))
    normalised_unique = int(lowered.nunique(dropna=True))

    flags = _name_flags(name)
    skew, zero_inflation, outlier_rate = _shape_moments(numeric.dropna())

    return ColumnProfile(
        name=name,
        numeric_coercion_rate=float(numeric.notna().mean()) if len(values) else 0.0,
        date_coercion_rate=float(dates.notna().mean()) if len(values) else 0.0,
        mixed_type=bool(0.05 < numeric.notna().mean() < 0.95) if len(values) else False,
        missing_rate=float(series.isna().sum()) / n,
        sentinel_rate=float(sentinel_hits) / non_null,
        format_shapes=_value_shapes(values),
        categorical_variants=max(0, n_unique - normalised_unique),
        n_unique=n_unique,
        unique_ratio=n_unique / non_null,
        mean_token_length=float(as_text.str.split().str.len().mean()) if len(values) else 0.0,
        skew=skew,
        zero_inflation=zero_inflation,
        outlier_rate=outlier_rate,
        name_score=min(1.0, len(flags) / 3),
        name_flags=flags,
    )


def profile_table(df: pd.DataFrame) -> pd.DataFrame:
    """One row per column, sorted by name_score then missing_rate."""
    rows = [profile_column(df[col], str(col)).as_dict() for col in df.columns]
    out = pd.DataFrame(rows)
    if out.empty:
        return out
    return out.sort_values(["name_score", "missing_rate"], ascending=False).reset_index(drop=True)


def table_summary(profile: pd.DataFrame) -> dict:
    """Aggregate a table profile into the numbers that go into the dirtiness heatmap."""
    if profile.empty:
        return {"n_columns": 0}
    return {
        "n_columns": len(profile),
        "share_autogenerated_names": float(profile["name_flags"].apply(lambda f: "autogenerated" in f).mean()),
        "share_flagged_names": float(profile["name_flags"].apply(bool).mean()),
        "share_mixed_type": float(profile["mixed_type"].mean()),
        "mean_missing_rate": float(profile["missing_rate"].mean()),
        "mean_sentinel_rate": float(profile["sentinel_rate"].mean()),
        # Every other dimension is "true if any column exhibits it", so D3 must be too.
        # Instacart's days_since_prior_order is null for 6 % of rows — structural, since a
        # user's first order has no predecessor — and a mean across seven columns dilutes
        # that to 0.9 %, below the threshold, hiding the dimension the table most clearly
        # has.
        "max_missing_rate": float(profile["missing_rate"].max()),
        "max_sentinel_rate": float(profile["sentinel_rate"].max()),
        "mean_format_shapes": float(profile["format_shapes"].mean()),
        # D4 only counts columns that are mostly numeric or mostly date, because that is
        # what "several number formats or date formats in one column" means. Free text and
        # identifiers carry arbitrary shapes without being format-heterogeneous.
        "share_typed_with_variants": float(
            (
                (
                    (profile["numeric_coercion_rate"] > 0.5)
                    | (profile["date_coercion_rate"] > 0.5)
                )
                & (profile["format_shapes"] > 1)
            ).mean()
        ),
        # D5 is about one entity written several ways, so it is restricted to columns that
        # actually have a small vocabulary. In free text every value is "unique except for
        # casing", which trips the raw variant count without there being any entity to
        # normalise — a category column is where case/whitespace variants mean something.
        "share_variant_categorical": float(
            ((profile["categorical_variants"] > 0) & (profile["unique_ratio"] < 0.5)).mean()
        ),
        "mean_unique_ratio": float(profile["unique_ratio"].mean()),
        "max_abs_skew": float(profile["skew"].abs().max()),
        "mean_zero_inflation": float(profile["zero_inflation"].mean()),
        "max_outlier_rate": float(profile["outlier_rate"].max()),
        # D6 texture is free text (many words per value) or a constant column. A unique
        # single-token column is an id, which every table has; counting those would make
        # the dimension fire everywhere and discriminate nothing.
        "share_freetext": float(
            (
                (profile["unique_ratio"] > 0.95)
                & (profile["mean_token_length"] >= 3)
            ).mean()
        ),
        "n_constant_columns": int((profile["unique_ratio"] == 0).sum()),
    }


# ---------------------------------------------------------------------------------------
# D1-D7 as booleans. The thresholds are declared once so that the triage gate (G4), the
# dirtiness heatmap and the M4 ablation all read the same definition of "this dimension is
# present". A table "has" a dimension when at least one column does.
# ---------------------------------------------------------------------------------------
DIMENSION_FLAGS: dict[str, str] = {
    "D1": "share_flagged_names > 0",
    "D2": "share_mixed_type > 0",
    "D3": "max_missing_rate > 0.01 or max_sentinel_rate > 0.005",
    "D4": "share_typed_with_variants > 0",
    "D5": "share_variant_categorical > 0",
    "D6": "share_freetext > 0 or n_constant_columns > 0",
    "D7": "max_abs_skew > 2 or mean_zero_inflation > 0.5 or max_outlier_rate > 0.05",
}


def dimension_flags(summary: dict) -> dict[str, bool]:
    """Which of D1-D7 a table exhibits, from its ``table_summary``."""
    if not summary or not summary.get("n_columns"):
        return dict.fromkeys(DIMENSION_FLAGS, False)
    return {
        "D1": summary["share_flagged_names"] > 0,
        "D2": summary["share_mixed_type"] > 0,
        "D3": summary["max_missing_rate"] > 0.01 or summary["max_sentinel_rate"] > 0.005,
        "D4": summary["share_typed_with_variants"] > 0,
        "D5": summary["share_variant_categorical"] > 0,
        "D6": summary["share_freetext"] > 0 or summary["n_constant_columns"] > 0,
        "D7": (
            summary["max_abs_skew"] > 2
            or summary["mean_zero_inflation"] > 0.5
            or summary["max_outlier_rate"] > 0.05
        ),
    }
