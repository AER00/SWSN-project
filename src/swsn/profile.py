"""Dirtiness profiling — dimensions D1-D7 (milestone2-plan.md §3.1).

These are v1 heuristics, deliberately simple and explainable: every number has to be
defensible in the report, so nothing here is a learned score. Refine in M3 if a dimension
turns out to discriminate poorly.
"""

from __future__ import annotations

import re
from dataclasses import asdict, dataclass

import pandas as pd

AUTOGENERATED = re.compile(r"^(unnamed:?\s*\d+|col_?\d+|v\d+|field\d+|column\d+)$", re.IGNORECASE)
SENTINELS = {"n/a", "na", "-", "--", "unknown", "?", "null", "none", "", "nan", "999", "-1"}


@dataclass(frozen=True)
class ColumnProfile:
    name: str
    # D2 type instability
    numeric_coercion_rate: float
    date_coercion_rate: float
    mixed_type: bool
    # D3 missingness and sentinels
    missing_rate: float
    sentinel_rate: float
    # D4 format heterogeneity
    format_shapes: int
    # D5 categorical noise
    categorical_variants: int
    # D6 cardinality and texture
    n_unique: int
    unique_ratio: float
    mean_token_length: float
    # D1 header noise (0 = clean name, 1 = unusable name)
    name_score: float
    name_flags: list[str]

    def as_dict(self) -> dict:
        return asdict(self)


def _value_shapes(series: pd.Series, limit: int = 2000) -> int:
    """Distinct 'shapes' of the values: digits -> 9, letters -> a, everything else kept.

    A column holding both ``1,234.5`` and ``1234.50`` yields two shapes — that is the
    point: this counts encoding heterogeneity, not value heterogeneity."""
    sample = series.dropna().astype(str).head(limit)
    shapes = {
        re.sub(r"\d", "9", re.sub(r"[A-Za-z]", "a", value.strip()))
        for value in sample
    }
    return len(shapes)


def _name_flags(name: str) -> list[str]:
    flags = []
    if AUTOGENERATED.match(name.strip()):
        flags.append("autogenerated")
    if any(ord(ch) > 127 for ch in name):
        flags.append("non_ascii")
    if re.search(r"[\(\[].*[\)\]]", name):
        flags.append("unit_in_header")
    if " " in name.strip():
        flags.append("spaces")
    if re.search(r"[A-Z]", name) and re.search(r"[a-z]", name) and "_" not in name:
        flags.append("camel_case")
    if len(name) <= 3:
        flags.append("abbreviated")
    return flags


def profile_column(series: pd.Series, name: str | None = None) -> ColumnProfile:
    name = name if name is not None else str(series.name)
    values = series.dropna()
    n = max(len(series), 1)
    non_null = max(len(values), 1)

    as_text = values.astype(str).str.strip()
    numeric = pd.to_numeric(as_text.str.replace(",", ".", regex=False), errors="coerce")
    dates = pd.to_datetime(as_text, errors="coerce", format="mixed")

    lowered = as_text.str.lower()
    sentinel_hits = lowered.isin(SENTINELS).sum()
    n_unique = int(values.nunique(dropna=True))
    normalised_unique = int(lowered.nunique(dropna=True))

    flags = _name_flags(name)

    return ColumnProfile(
        name=name,
        numeric_coercion_rate=float(numeric.notna().mean()) if len(values) else 0.0,
        date_coercion_rate=float(dates.notna().mean()) if len(values) else 0.0,
        mixed_type=bool(0.05 < numeric.notna().mean() < 0.95) if len(values) else False,
        missing_rate=float(series.isna().sum()) / n,
        sentinel_rate=float(sentinel_hits) / non_null,
        format_shapes=_value_shapes(values),
        categorical_variants=max(0, n_unique - normalised_unique),
        n_unique=n_unique,
        unique_ratio=n_unique / non_null,
        mean_token_length=float(as_text.str.split().str.len().mean()) if len(values) else 0.0,
        name_score=min(1.0, len(flags) / 3),
        name_flags=flags,
    )


def profile_table(df: pd.DataFrame) -> pd.DataFrame:
    """One row per column, sorted by name_score then missing_rate."""
    rows = [profile_column(df[col], str(col)).as_dict() for col in df.columns]
    out = pd.DataFrame(rows)
    if out.empty:
        return out
    return out.sort_values(["name_score", "missing_rate"], ascending=False).reset_index(drop=True)


def table_summary(profile: pd.DataFrame) -> dict:
    """Aggregate a table profile into the numbers that go into the dirtiness heatmap."""
    if profile.empty:
        return {"n_columns": 0}
    return {
        "n_columns": len(profile),
        "share_autogenerated_names": float(profile["name_flags"].apply(lambda f: "autogenerated" in f).mean()),
        "share_mixed_type": float(profile["mixed_type"].mean()),
        "mean_missing_rate": float(profile["missing_rate"].mean()),
        "mean_sentinel_rate": float(profile["sentinel_rate"].mean()),
        "mean_format_shapes": float(profile["format_shapes"].mean()),
        "share_with_variants": float((profile["categorical_variants"] > 0).mean()),
        "mean_unique_ratio": float(profile["unique_ratio"].mean()),
    }
